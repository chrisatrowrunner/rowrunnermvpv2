// menu-sql.mjs — print the Supabase `menu_prices` SQL from src/data/menu.ts.
//
// The Netlify payment function charges from `menu_prices`, so it must match
// the menu the app shows. Never hand-edit prices in SQL; change menu.ts, then:
//
//   npm run menu:sql > supabase/menu-prices.sql
//
// …and run that file in Supabase (SQL Editor) BEFORE deploying the app.
import { readFileSync } from 'node:fs'
import { transformSync } from 'esbuild'

const src = readFileSync(new URL('../src/data/menu.ts', import.meta.url), 'utf8')
const { code } = transformSync(src, { loader: 'ts', format: 'esm' })
const { MENU } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'))

const cents = (dollars) => Math.round(dollars * 100)
const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const deltas = (pairs) => q(JSON.stringify(Object.fromEntries(pairs)))

// Comma goes BEFORE the trailing comment (a comma after `--` would be ignored).
const rows = MENU.map((m, i) => {
  const options = deltas((m.options?.choices ?? []).map((c) => [c.name, cents(c.d)]))
  const addons = deltas(m.addons.map((a) => [a.name, cents(a.d)]))
  const sep = i < MENU.length - 1 ? ',' : ''
  return `  (${q(m.id)}, ${cents(m.price)}, ${options}, ${addons})${sep}  -- ${m.name} $${m.price.toFixed(2)}`
})

const ids = MENU.map((m) => q(m.id)).join(', ')

process.stdout.write(`-- menu-prices.sql — server-side source of truth for charging.
-- GENERATED by \`npm run menu:sql\` from src/data/menu.ts — do not hand-edit.
-- The Netlify create-payment-intent function totals an order from THESE prices
-- (never the amount the client sends), so a tampered client can't underpay.
--
-- Run in Supabase: SQL Editor ▸ New query ▸ paste ▸ Run — BEFORE deploying the
-- app, or new items fail at checkout with "Unknown item". Safe to re-run.
-- Prices are in CENTS.

create table if not exists public.menu_prices (
  item_id    text primary key,
  base_cents int  not null,
  -- option name → price delta in cents, e.g. {"Double": 300}
  options    jsonb not null default '{}',
  -- addon name → price delta in cents, e.g. {"Bacon": 200}
  addons     jsonb not null default '{}'
);

alter table public.menu_prices enable row level security;
drop policy if exists "anyone can read prices" on public.menu_prices;
create policy "anyone can read prices" on public.menu_prices for select using (true);

begin;

-- drop items that are no longer on the menu
delete from public.menu_prices where item_id not in (${ids});

insert into public.menu_prices (item_id, base_cents, options, addons) values
${rows.join('\n')}
on conflict (item_id) do update
  set base_cents = excluded.base_cents,
      options    = excluded.options,
      addons     = excluded.addons;

commit;

-- Stripe PaymentIntent id, stored on the order once payment succeeds.
alter table public.orders add column if not exists payment_ref text;
grant select (payment_ref) on public.orders to anon, authenticated;
`)
